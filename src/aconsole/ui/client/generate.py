"""Write `typed_facade.py`: one typed async method per `METHODS` row (APP_API §9).

Run `python -m aconsole.ui.client.generate` after a change to `METHODS` or `BINDINGS`; `check_contracts` fails
while the file on disk differs from `render()`.
"""

import re
import sys
from pathlib import Path

from aconsole.contracts.methods import METHODS
from aconsole.ui.client.methods import BINDINGS

TARGET = Path(__file__).with_name("typed_facade.py")
_WORD = re.compile(r"[A-Z]")


def method_name(rpc: str) -> str:
    """`tab/launchSpec` -> `tab_launch_spec`."""
    snake = _WORD.sub(lambda found: "_" + found.group(0).lower(), rpc)
    return snake.replace("/", "_").replace("$", "").strip("_")


def render() -> str:
    rows = [BINDINGS[method.name] for method in METHODS]
    modules: dict[str, set[str]] = {}
    for row in rows:
        for kind in (row.params, row.result):
            modules.setdefault(kind.__module__, set()).add(kind.__name__)
    lines = [
        '"""Generated by `python -m aconsole.ui.client.generate` from `METHODS`. Do not edit."""',
        "",
    ]
    for module in sorted(modules):
        names = sorted(modules[module], key=lambda name: (name.lower(), name))
        lines.append(f"from {module} import (")
        lines.extend(f"    {name}," for name in names)
        lines.append(")")
    lines.extend(
        [
            "from aconsole.ui.client.methods import Facade",
            "",
            "",
            "class TypedFacade(Facade):",
            '    """Every `METHODS` row as a typed method. The result type is checked at run time."""',
        ]
    )
    for row in rows:
        lines.extend(
            [
                "",
                f"    async def {method_name(row.name)}(self, params: {row.params.__name__}) -> {row.result.__name__}:",
                f'        return await self.typed("{row.name}", params, {row.result.__name__})',
            ]
        )
    return "\n".join(lines) + "\n"


def main() -> int:
    _ = TARGET.write_text(render(), encoding="utf-8")
    _ = sys.stdout.write(f"wrote {TARGET}\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
